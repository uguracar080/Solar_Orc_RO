function cond_out = condenser_aircooled_UA_and_fan(orc, out, cond)
% Air-cooled condenser iÃ§in UA_required ve fan gÃ¼cÃ¼ hesapla.
% VarsayÄ±m:
% - Refrigerant kondenzasyon sÄ±caklÄ±ÄŸÄ± ~ Tcond_sat (Pcondâ€™de)
% - SÄ±cak taraf faz deÄŸiÅŸimi: C_r ~ 0 (sÄ±cak taraf kapasite sonsuz)
% - Îµâ€“NTU: Îµ = 1 - exp(-NTU)
% - Q = Îµ * Cmin * (Tcond - Tair_in)

cond_out = struct();                                                               % Ã‡Ä±ktÄ±

% ORC Ã§Ã¶zÃ¼mÃ¼ baÅŸarÄ±lÄ± deÄŸilse boÅŸ dÃ¶n
if ~out.ok
    cond_out.ok  = false;
    cond_out.msg = 'ORC not solved -> condenser skipped.';
    return
end

fluid = orc.fluid;                                                                 % ORC akÄ±ÅŸkanÄ±
Pcond = orc.P_cond_bar * 1e5;                                                      % [Pa]

Tcond_sat_K = PropsSI('T','P',Pcond,'Q',0,fluid);                                  % Kondenzasyon sÄ±caklÄ±ÄŸÄ± [K]
Qcon_W = out.Qcon_kW * 1000;                                                       % Kondenser yÃ¼kÃ¼ [W]

Tair_in_K = cond.Tair_in_C + 273.15;                                               % Hava giriÅŸ [K]
mdot_air  = cond.mdot_air_kg_s;                                                    % Hava debisi [kg/s]
cp_air    = cond.cp_air_JkgK;                                                      % cp [J/kgK]

Cmin = mdot_air * cp_air;                                                          % Hava kapasite oranÄ± [W/K]
Qmax_W = Cmin * (Tcond_sat_K - Tair_in_K);                                         % Maks mÃ¼mkÃ¼n Ä±sÄ± [W]

cond_out.Tcond_sat_C = Tcond_sat_K - 273.15;                                       % [Â°C]
cond_out.Qcon_kW     = Qcon_W/1000;                                                % [kW]
cond_out.Qmax_kW     = Qmax_W/1000;                                                % [kW]

if Qcon_W <= 0
    cond_out.ok  = false;
    cond_out.msg = 'Invalid Qcon (<=0).';
    return
end
if Qcon_W >= Qmax_W
    cond_out.ok  = false;
    cond_out.msg = sprintf('Condenser infeasible: Qcon=%.2f kW >= Qmax=%.2f kW.', Qcon_W/1000, Qmax_W/1000);
    return
end

epsilon = Qcon_W / Qmax_W;                                                         % Îµ
NTU = -log(1 - epsilon);                                                           % Îµ = 1-exp(-NTU) => NTU=-ln(1-Îµ)
UA_WK = NTU * Cmin;                                                                % UA

% Hava Ã§Ä±kÄ±ÅŸ sÄ±caklÄ±ÄŸÄ± (enerji dengesi)
Tair_out_K = Tair_in_K + Qcon_W / Cmin;                                            % [K]

% ---- Hava tarafÄ± basÄ±nÃ§ kaybÄ± ve fan gÃ¼cÃ¼ ----
rho_air = PropsSI('D','T',Tair_in_K,'P',cond.Pamb_Pa,'Air');                       % YoÄŸunluk [kg/m3]
cond_out.rho_air = rho_air;                                                        % Kaydet

dp_air = NaN;                                                                      % Î”p

if strcmpi(cond.dp_model, 'K_dp')
    % Basit temsil: Î”p = K*(0.5*rho*V^2)
    dp_air = cond.K_dp * (0.5 * rho_air * cond.V_face_ms^2);                       % [Pa]
elseif strcmpi(cond.dp_model, 'yumrutas_bank')
    % YumrutaÅŸ (2002) fin-tube bank basÄ±nÃ§ kaybÄ± formu (parametrik)
    % Î”p = (G^2 * v_in /2) * [ (1+Ïƒ^2)*(v_out/v_in - 1) + f*(A/A_ff)*(v_m/v_in) ]
    sigma_b = cond.bank.sigma;
    f_b     = cond.bank.f;
    A       = cond.bank.A;
    A_ff    = cond.bank.A_ff;
    G       = cond.bank.G_kg_m2s;
    v_in    = 1/rho_air;
    v_out   = v_in;                                                                % Ä°lk yaklaÅŸÄ±m: Ã§ok kÃ¼Ã§Ã¼k Ä±sÄ±nma -> v_outâ‰ˆv_in
    v_m     = v_in;
    dp_air  = (G^2 * v_in / 2) * ( (1+sigma_b^2)*(v_out/v_in - 1) + f_b*(A/A_ff)*(v_m/v_in) );
else
    dp_air = NaN;
end

cond_out.dp_air_Pa = dp_air;                                                       % Kaydet

% YumrutaÅŸ (2002) fan Ã¶zgÃ¼l iÅŸi yaklaÅŸÄ±mÄ±:
% w_fan â‰ˆ (Î”p / Ï_in) / Î·_fan    (m^2/s^2 = J/kg)
% Fan gÃ¼cÃ¼: Wfan = mdot_air * w_fan
w_fan_Jkg = (dp_air / rho_air) / max(cond.eta_fan,1e-6);                           % [J/kg]
Wfan_W    = mdot_air * w_fan_Jkg;                                                  % [W]

cond_out.epsilon   = epsilon;                                                      % eps
cond_out.NTU       = NTU;                                                          % NTU
cond_out.UA_WK     = UA_WK;                                                        % UA
cond_out.Tair_out_C = Tair_out_K - 273.15;                                         % [Â°C]
cond_out.Wfan_kW    = Wfan_W/1000;                                                 % [kW]
cond_out.ok         = true;                                                        % OK
cond_out.msg        = 'OK';                                                        % Mesaj
end

%% =================================================================================================
%% LOCAL FUNCTION: System Exergy Analysis (PTC + HX + ORC)
%% =================================================================================================
function ex = exergy_analysis_system(ptc_field, ptc, field, hx_out, waste, evap_hot, orc, out, cond_out, cfg)
% exergy_analysis_system
%   V9 yapÄ±sÄ±na uyumlu exergy hesabÄ±:
%   ORC state'leri out.states(3,4,5,6) iÃ§indedir ve alanlar:
%   P_bar, T_C, h_kJkg, s_kJkgK
%
% VarsayÄ±mlar:
%   - KE/PE ihmal
%   - IsÄ± transfer exergy'si iÃ§in sÄ±nÄ±r sÄ±caklÄ±ÄŸÄ± ~ doyma sÄ±caklÄ±ÄŸÄ± kabulÃ¼
%   - Hava tarafÄ± detaylarÄ± yoksa kondenserde "minimum" yaklaÅŸÄ±m

ex = struct();

% -------------------------
% 0) GÃ¼venli okuma yardÄ±mcÄ±larÄ±
% -------------------------
T0 = cfg.T0_K;
P0 = cfg.P0_kPa*1e3;   % [Pa]
fluid = orc.fluid;

if ~isfield(evap_hot,'Tout_K') || ~isfinite(evap_hot.Tout_K)                         % Tout yoksa
    ex.ok = false;                                                                   % fail
    ex.msg = "evap_hot.Tout_K missing/NaN -> cannot compute evaporator exergy.";     % mesaj
    return                                                                           % Ã§Ä±k
end



% out.states mevcut mu?
if ~isfield(out,'states') || numel(out.states) < 6
    warning('out.states bulunamadÄ± veya 6 state yok. Exergy hesap atlandÄ±.');
    ex.ok = false;
    return;
end

% Her state iÃ§in h,s oku (J/kg ve J/kg-K)
[h3,s3,T3K,P3Pa] = get_state_hs(out.states,3);
[h4,s4,T4K,P4Pa] = get_state_hs(out.states,4);
[h5,s5,T5K,P5Pa] = get_state_hs(out.states,5);
[h6,s6,T6K,P6Pa] = get_state_hs(out.states,6);

mdot = out.mdot_r;   % ORC kÃ¼tlesel debisi [kg/s] (V9'da out.mdot_r var)

% out.Wt_kW vb. var, W deÄŸerlerini al (W)
Wt_W  = out.Wt_kW*1000;
Wp_W  = out.Wp_kW*1000;

% IsÄ± yÃ¼kleri (W)
Qev_W  = out.Qev_kW*1000;   % ORC evaporatÃ¶r Ä±sÄ± giriÅŸi (pozitif)
Qcon_W = out.Qcon_kW*1000;  % ORC kondenser Ä±sÄ± atÄ±mÄ± (pozitif)

% -------------------------
% 1) Dead-state (h0,s0) aynÄ± akÄ±ÅŸkan iÃ§in
% -------------------------
h0 = PropsSI('H','T',T0,'P',P0,fluid);
s0 = PropsSI('S','T',T0,'P',P0,fluid);

% -------------------------
% 2) Specific flow exergy (J/kg)
%    e = (h-h0) - T0*(s-s0)
% -------------------------
e3 = (h3-h0) - T0*(s3-s0);
e4 = (h4-h0) - T0*(s4-s0);
e5 = (h5-h0) - T0*(s5-s0);
e6 = (h6-h0) - T0*(s6-s0);

% Exergy rate (W)
Ex3 = mdot*e3;
Ex4 = mdot*e4;
Ex5 = mdot*e5;
Ex6 = mdot*e6;

% -------------------------
% 3) BileÅŸen exergy yÄ±kÄ±mÄ± (ExD) â€“ iÅŸaretler pozitif olacak ÅŸekilde
% -------------------------

% 3.1 Pompa: ExD = W_in - (Ex_out - Ex_in)
ExD_pump = Wp_W - (Ex6 - Ex5);

% 3.2 TÃ¼rbin: ExD = (Ex_in - Ex_out) - W_out
ExD_turb = (Ex3 - Ex4) - Wt_W;

% 3.3 EvaporatÃ¶r: ExD = (Ex_in + Ex_Qin) - Ex_out
% ------------------------- EVAPORATOR: 2-STREAM EXERGY DESTRUCTION -------------------------

% Hot tarafÄ± alan adlarÄ± (senin evap_hot struct'Ä±na gÃ¶re)
Th_in_K  = evap_hot.Tin_K;                                                        % Hot inlet temperature [K]
Th_out_K = evap_hot.Tout_K;                                                       % Hot outlet temperature [K]
Ph_Pa    = evap_hot.P_bar * 1e5;                                                  % Hot pressure [Pa]
mdot_h   = evap_hot.mdot_kg_s;                                                    % Hot mass flow rate [kg/s]
fluid_hot = evap_hot.fluid;                                                       % Hot fluid name (Water)

% Hot inlet h,s [J/kg , J/kg-K]
h_h_in = PropsSI('H','T',Th_in_K ,'P',Ph_Pa,fluid_hot);                           % Hot inlet enthalpy
s_h_in = PropsSI('S','T',Th_in_K ,'P',Ph_Pa,fluid_hot);                           % Hot inlet entropy

% Hot outlet h,s [J/kg , J/kg-K]
h_h_out = PropsSI('H','T',Th_out_K,'P',Ph_Pa,fluid_hot);                          % Hot outlet enthalpy
s_h_out = PropsSI('S','T',Th_out_K,'P',Ph_Pa,fluid_hot);                          % Hot outlet entropy

% Hot dead-state h0,s0 [J/kg , J/kg-K]
h0_h = PropsSI('H','T',T0,'P',P0,fluid_hot);                                      % Dead-state enthalpy (hot)
s0_h = PropsSI('S','T',T0,'P',P0,fluid_hot);                                      % Dead-state entropy  (hot)

% Hot specific flow exergy [J/kg]
e_h_in  = (h_h_in  - h0_h) - T0*(s_h_in  - s0_h);                                 % Hot inlet specific exergy
e_h_out = (h_h_out - h0_h) - T0*(s_h_out - s0_h);                                 % Hot outlet specific exergy

% Hot exergy rates [W]
Ex_h_in  = mdot_h * e_h_in;                                                       % Hot inlet exergy rate
Ex_h_out = mdot_h * e_h_out;                                                      % Hot outlet exergy rate

% WF tarafÄ± exergy rate'leri zaten hesaplandÄ±: Ex6 (evap inlet), Ex3 (evap outlet)
Ex_wf_in  = Ex6;                                                                   % WF inlet exergy rate [W]
Ex_wf_out = Ex3;                                                                   % WF outlet exergy rate [W]

% EvaporatÃ¶r exergy destruction (2-stream bilanÃ§o) [W]
ExD_evap = (Ex_h_in + Ex_wf_in) - (Ex_h_out + Ex_wf_out);                         % Evaporator ExD [W]



% KaÅŸka Case-1 iÃ§in exergy input: hot akÄ±ÅŸkandan Ã§ekilen exergy [W]
Ex_in_hot = (Ex_h_in - Ex_h_out);                                                 % Exergy extracted from hot stream [W]

if ~isfinite(ExD_evap)                                                               % NaN/Inf korumasÄ±
    ExD_evap = NaN;                                                                  % iÅŸaretle
end
if isfinite(ExD_evap) && ExD_evap < 0                                                % negatif yÄ±kÄ±m fiziksel deÄŸil
    ExD_evap = max(0, ExD_evap);                                                     % 0'a kÄ±rp (sayÄ±sal)
end


% 3.4 Kondenser: ExD = Ex_in - (Ex_out + Ex_Qout)
% SÄ±nÄ±r sÄ±caklÄ±ÄŸÄ±: out.Tcond_sat_C varsa onu kullan, yoksa state-5/4 ortalamasÄ±
if isfield(out,'Tcond_sat_C')
    Tb_cd = out.Tcond_sat_C + 273.15;
else
    Tb_cd = 0.5*(T4K + T5K);
end
ExQ_out = Qcon_W * max(0, (1 - T0/max(Tb_cd,1)));


% Kondenser exergy destruction (minimum approximation)
% ExD = (Ex_in - Ex_out) - Ex_Q_out    (Q_out Ã§evreye giden Ä±sÄ±)
ExD_cond = (Ex4 - Ex5) - ExQ_out;                                                  % [W]
%ExD_cond = (Ex4) - (Ex5 + ExQ_out);
ExD_cond = max(0, ExD_cond);                                                       % SayÄ±sal negatifleri sÄ±fÄ±ra kÄ±rp (fiziksel gÃ¼venlik)


% Toplam
ExD_total = ExD_pump + ExD_turb + ExD_evap + ExD_cond;

% -------------------------
% 4) Solar exergy (Petela) â€“ ptc.A_ap ve ptc.Gb varsa
% -------------------------

Ex_solar = NaN;                                                                    % VarsayÄ±lan
eta_ex_ptc = NaN;                                                                  % PTC exergy verimi (opsiyonel)

if isfield(ptc_field,'Aa_m2') && isfield(ptc_field,'Gb_Wm2') && ptc_field.Aa_m2>0 && ptc_field.Gb_Wm2>0
    phi_petela = 1 - (4/3)*(T0/cfg.T_sun_K) + (1/3)*(T0/cfg.T_sun_K)^4;            % Petela faktÃ¶rÃ¼
    Ex_solar   = ptc_field.Aa_m2 * ptc_field.Gb_Wm2 * phi_petela;                  % [W]
    
    % PTCâ€™den Ã§Ä±kan faydalÄ± Ä±sÄ± (Qu_total_W) Ã¼zerinden PTC exergy verimi (basit yaklaÅŸÄ±m)
    % Not: LiteratÃ¼rde PTC exergy verimi farklÄ± tanÄ±mlarla da verilir; bunu istersen sonra rafine ederiz.
    eta_ex_ptc = (ptc_field.Qu_total_W) / max(Ex_solar,1e-12);                     % [-] (basit)
end

ex.Ex_solar_kW = Ex_solar/1000;                                                    % [kW]
ex.eta_ex_ptc  = eta_ex_ptc;                                                       % [-]



% ------------------------- ORC EXERGY EFFICIENCY (KaÅŸka Case-1) -------------------------
eta_ex_orc = NaN;
if Ex_in_hot > 0                                                                    % Hot exergy input pozitifse
    eta_ex_orc = (out.Wnet_kW*1000) / Ex_in_hot;                                   % [-]
else
    eta_ex_orc = NaN;                                                              % tanÄ±msÄ±z
end



% -------------------------
% 5) Ã‡Ä±ktÄ± struct
% -------------------------
ex.ok = true;

ex.e3 = e3; ex.e4 = e4; ex.e5 = e5; ex.e6 = e6;
ex.Ex3_W = Ex3; ex.Ex4_W = Ex4; ex.Ex5_W = Ex5; ex.Ex6_W = Ex6;

ex.ExD_pump_kW  = ExD_pump/1000;
ex.ExD_turb_kW  = ExD_turb/1000;
ex.ExD_evap_kW  = ExD_evap/1000;
ex.ExD_cond_kW  = ExD_cond/1000;
ex.ExD_total_kW = ExD_total/1000;
ex.Ex_in_hot_kW = Ex_in_hot/1000;                                                 % [kW] (KaÅŸka tanÄ±mÄ±)


ex.Ex_solar_kW  = Ex_solar/1000;
ex.eta_ex_orc   = eta_ex_orc;

% ------------------------- DEBUG: EVAP EXERGY TERMS -------------------------
if cfg.verbose                                                                          % KullanÄ±cÄ± verbose istiyorsa
    fprintf("\n[EX-DBG] Evap hot: Tin=%.2f C, Tout=%.2f C, P=%.3f bar, mdot=%.4f kg/s\n", ...
        Th_in_K-273.15, Th_out_K-273.15, evap_hot.P_bar, mdot_h);                      % Hot akÄ±ÅŸkan giriÅŸ/Ã§Ä±kÄ±ÅŸ/P/mdot

    fprintf("[EX-DBG] Ex_h_in=%.3f kW, Ex_h_out=%.3f kW, (Ex_h_in-Ex_h_out)=%.3f kW\n", ...
        Ex_h_in/1000, Ex_h_out/1000, (Ex_h_in-Ex_h_out)/1000);                         % Hot exergy oranlarÄ±

    fprintf("[EX-DBG] Ex_wf_in(6)=%.3f kW, Ex_wf_out(3)=%.3f kW, (Ex_wf_out-Ex_wf_in)=%.3f kW\n", ...
        Ex6/1000, Ex3/1000, (Ex3-Ex6)/1000);                                            % WF exergy deÄŸiÅŸimi

    fprintf("[EX-DBG] ExD_evap=%.3f kW\n", ExD_evap/1000);                               % Evap yÄ±kÄ±mÄ±
end


end

