    out.eta_th  = Wnet_W / max(Qev_W,1e-9);                                        % [-]
    out.energy_closure_kW = out.Qev_kW - out.Qcon_kW - out.Wnet_kW;                % [kW] (ideal 0)

    % -------------------------
    % 11) Son fiziksel kontroller
    % -------------------------
    if Thot_out_K >= Thot_pp_K
        error('Physical check failed: Thot_out >= Thot_pp (preheat zone invalid).');
    end

    out.ok  = true;                                                                % OK
    out.msg = 'OK';                                                                % mesaj

catch ME
    out.ok  = false;                                                               % fail
    out.msg = ME.message;                                                          % hata mesajÄ±
end
end

% =====================================================================
% === Local residual function (2 eq) ==================================
% =====================================================================
function F = residual_evap2zone_UA(x, Thot_in_K, Thot_pp_K, mdot_hot, ...
                                   hot, orc, sp, Tevap_K, T6_K, hf, h3, h6, ...
                                   UA_evap, UA_pre, cfg)
% x(1)=mdot_r, x(2)=Thot_out_K iÃ§in 2 residual Ã¼retir.

mdot_r     = x(1);                                                                 % ORC debisi
Thot_out_K = x(2);                                                                 % Hot Ã§Ä±kÄ±ÅŸ

% --- Fiziksel sÄ±nÄ±rlar (fsolve stabilitesi iÃ§in) ---
mdot_r = max(mdot_r, 1e-6);                                                        % negatif/0 olmasÄ±n
Thot_out_K = min(Thot_out_K, Thot_pp_K - 1e-6);                                    % pp'den bÃ¼yÃ¼k olmasÄ±n
Thot_out_K = max(Thot_out_K, 273.15);                                              % aÅŸÄ±rÄ± dÃ¼ÅŸÃ¼k olmasÄ±n

% --- Zon-1 (evap) UA Ä±sÄ± ---
DT1_ev = Thot_in_K - Tevap_K;                                                      % uÃ§ 1
DT2_ev = Thot_pp_K - Tevap_K;                                                      % uÃ§ 2
LMTD_evap = safe_lmtd(DT1_ev, DT2_ev);                                             % LMTD
Q_evap_UA = UA_evap * LMTD_evap;                                                   % [W]

% ORC evaporation ihtiyacÄ±
Q_evap_ORC = mdot_r * (h3 - hf);                                                   % [W]

% --- Zon-2 (preheat) UA Ä±sÄ± ---
DT1_pr = Thot_pp_K - Tevap_K;                                                      % uÃ§ 1
DT2_pr = Thot_out_K - T6_K;                                                        % uÃ§ 2

% DT2_pr <= 0 ise LMTD tanÄ±msÄ±z -> residual bÃ¼yÃ¼k ceza
if DT2_pr <= 1e-6
    Q_pre_UA = 0;                                                                  % sayÄ±sal
else
    LMTD_pre = safe_lmtd(DT1_pr, DT2_pr);                                          % LMTD
    Q_pre_UA = UA_pre * LMTD_pre;                                                  % [W]
end

% ORC preheat ihtiyacÄ± (mdot_r ile)
Q_pre_ORC = mdot_r * (hf - h6);                                                    % [W]

% --- Hot tarafÄ± saÄŸlanabilen toplam Ä±sÄ± (integral) ---
Q_hot_available = hot_Qdot_integral(mdot_hot, Thot_in_K, Thot_out_K, hot.fluid, hot.P_bar, cfg); % [W]

% --- Denklem-1: Evap zonu eÅŸleÅŸsin ---
F1 = Q_evap_UA - Q_evap_ORC;                                                       % =0

% --- Denklem-2: Toplam UA Ä±sÄ± = Hot'tan Ã§ekilen Ä±sÄ± ---
F2 = (Q_evap_UA + Q_pre_UA) - Q_hot_available;                                     % =0

% (Ä°stersen Ã¼Ã§Ã¼ncÃ¼ kontrol: Q_pre_UA - Q_pre_ORC -> rapor amaÃ§lÄ± kontrol edebilirsin,
% ama Ã§Ã¶zÃ¼mde 2 denklem tutuyoruz.)

F = [F1; F2];                                                                      % 2x1 residual
end

% =====================================================================
% === Safe LMTD helper ================================================
% =====================================================================
function LMTD = safe_lmtd(DT1, DT2)
% LMTD = (DT1-DT2)/ln(DT1/DT2) numerik olarak DT1~DT2 durumunda patlamasÄ±n.

DT1 = max(DT1, 1e-12);                                                             % gÃ¼venlik
DT2 = max(DT2, 1e-12);                                                             % gÃ¼venlik

if abs(DT1 - DT2) < 1e-9                                                           % DT1 ~ DT2 ise
    LMTD = 0.5*(DT1 + DT2);                                                        % limit -> aritmetik ort.
else
    LMTD = (DT1 - DT2) / log(DT1/DT2);                                             % klasik LMTD
end
end


