function Qdot_W = hot_Qdot_integral(mdot, Tin_K, Tout_K, hotFluid, P_bar, cfg)
% Genel integral: Qdot = mdot * âˆ« cp(T) dT  (Tin > Tout ise pozitif Ã§Ä±kar)
% HIZ: Water iÃ§in cp LUT varsa PropsSI yerine interp1 ile cp alÄ±r.

N = cfg.N_int;                                                                     % (HIZ) integral nokta sayÄ±sÄ±
Tvec = linspace(Tout_K, Tin_K, N);                                                 % Tout -> Tin sÄ±caklÄ±k vektÃ¶rÃ¼
cpvec = zeros(size(Tvec));                                                         % cp vektÃ¶rÃ¼

for i = 1:numel(Tvec)                                                              % integral dÃ¶ngÃ¼sÃ¼
    if strcmpi(hotFluid, 'syltherm800')                                            % SYLTHERM ise
        [~, cp, ~, ~] = syltherm800_props(Tvec(i));                                % cp [J/kgK]
        cpvec(i) = cp;                                                             % cp ata
    else
        P_Pa = P_bar * 1e5;                                                        % Pa'ya Ã§evir

        % (HIZ) LUT uygunsa cp'yi interpolasyonla al
        if isfield(cfg,'cpLUT') && isstruct(cfg.cpLUT) && isfield(cfg.cpLUT,'enabled') && cfg.cpLUT.enabled ...
                && strcmpi(hotFluid, cfg.cpLUT.fluid) && abs(P_Pa - cfg.cpLUT.P_Pa) < 1e-6
            cpvec(i) = interp1(cfg.cpLUT.T, cfg.cpLUT.cp, Tvec(i), 'linear', 'extrap'); % hÄ±zlÄ± cp
        else
            cpvec(i) = PropsSI('C','T',Tvec(i),'P',P_Pa,hotFluid);                 % fallback (yavaÅŸ)
        end
    end
end

dH_Jkg = trapz(Tvec, cpvec);                                                       % âˆ«cp dT [J/kg]
Qdot_W = mdot * dH_Jkg;                                                            % Qdot [W]
end

